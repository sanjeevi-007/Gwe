import 'dart:async';

import '../data/repositories/gps_repository.dart';
import '../models/enums.dart';
import '../models/gps_reading.dart';

/// Service bridging phone location services (or simulated phone GPS) into the GWEN Puck location feed.
///
/// When active, periodically generates valid [GpsReading] instances using coordinates
/// (lat, lon, altitude, satellites = 8, HDOP = 1.0, fixState = GpsFixState.fix) and streams/persists
/// them into the database sync engine.
class PhoneGpsBridge {
  final GpsRepository? gpsRepository;
  final StreamController<GpsReading> _gpsStreamController =
      StreamController<GpsReading>.broadcast();
  Timer? _timer;
  bool _isActive = false;

  double currentLat;
  double currentLon;
  double currentAltitude;
  int satellites;
  double hdop;

  PhoneGpsBridge({
    this.gpsRepository,
    this.currentLat = 37.7749,
    this.currentLon = -122.4194,
    this.currentAltitude = 15.0,
    this.satellites = 8,
    this.hdop = 1.0,
  });

  /// Stream of [GpsReading] packets generated by the phone GPS bridge.
  Stream<GpsReading> get gpsStream => _gpsStreamController.stream;

  /// Whether the phone GPS bridge is currently generating location telemetry.
  bool get isActive => _isActive;

  /// Starts the GPS bridge, periodically generating and persisting location telemetry.
  void start({
    Duration interval = const Duration(seconds: 1),
    double? initialLat,
    double? initialLon,
  }) {
    if (initialLat != null) currentLat = initialLat;
    if (initialLon != null) currentLon = initialLon;

    _isActive = true;
    _timer?.cancel();

    // Immediately emit initial coordinate
    _generateAndEmitReading();

    // Schedule periodic location updates
    _timer = Timer.periodic(interval, (_) {
      _generateAndEmitReading();
    });
  }

  /// Stops the GPS bridge.
  void stop() {
    _isActive = false;
    _timer?.cancel();
    _timer = null;
  }

  /// Generates a single [GpsReading] from current coordinates and emits to stream & repository.
  GpsReading _generateAndEmitReading() {
    final now = DateTime.now();

    final reading = GpsReading(
      deviceId: 'PHONE-GPS-BRIDGE',
      tsDevice: now,
      tsReceived: now,
      fixState: GpsFixState.fix,
      lat: currentLat,
      lon: currentLon,
      satellites: satellites,
      hdop: hdop,
      valid: true,
      stale: false,
    );

    if (!_gpsStreamController.isClosed) {
      _gpsStreamController.add(reading);
    }

    gpsRepository?.insertGps(reading);

    return reading;
  }

  /// Manually injects or updates phone GPS coordinates.
  GpsReading updateCoordinates({
    required double lat,
    required double lon,
    double? altitude,
  }) {
    currentLat = lat;
    currentLon = lon;
    if (altitude != null) currentAltitude = altitude;
    return _generateAndEmitReading();
  }

  /// Releases resources.
  void dispose() {
    stop();
    _gpsStreamController.close();
  }
}
